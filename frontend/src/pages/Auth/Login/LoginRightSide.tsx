import { useState, useEffect } from "react";
import { useAuth } from "../../../../context/AuthContext";
import { Link, useNavigate, useSearchParams } from "react-router-dom";
import axios from "axios";
import Mail from "@/src/components/Elements/Mail";
import Lock from "@/src/components/Elements/Lock";
import EyeOpen from "@/src/components/Elements/EyeOpen";
import EyeClose from "@/src/components/Elements/EyeClose";
import Arrow from "@/src/components/Elements/Arrow";
import AuthErrorAlert from "@/src/components/AuthErrorAlert";

function getAuthErrorMessage(error: unknown, fallback: string): string {
  if (!axios.isAxiosError(error)) {
    return fallback;
  }

  if (!error.response) {
    return "Unable to connect to the server. Make sure the backend is running.";
  }

  if (error.response.status === 401) {
    return "Incorrect credentials";
  }

  if (error.response.status === 503) {
    return "Authentication service not ready";
  }

  const message = error.response.data?.message;
  if (Array.isArray(message)) {
    return message.join(" ");
  }

  if (typeof message === "string" && message.length > 0) {
    if (message === "Invalid credentials") {
      return "Incorrect email or password.";
    }
    return message;
  }

  return `The server rejected the request (${error.response.status}).`;
}

export default function LoginRightSide() {
  const [email, setEmail] = useState<string>("");
  const [password, setPassword] = useState<string>("");
  const [showPassword, setShowPassword] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);

  // 2FA state
  const [requiresTwoFactor, setRequiresTwoFactor] = useState(false);
  const [userId, setUserId] = useState<string>("");
  const [code, setCode] = useState<string>("");

  const { login, oauth42, refreshUser } = useAuth();
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();

  useEffect(() => {
    const idFromUrl = searchParams.get("userId");
    if (idFromUrl) {
      setUserId(idFromUrl);
      setRequiresTwoFactor(true);
    }
  }, [searchParams]);

  // Submit credentials
  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    setErrorMessage(null);
    setIsSubmitting(true);
    try {
      const response = await login(email, password);

      // If the backend indicates 2FA is required
      if (response && response.requiresTwoFactor) {
        setRequiresTwoFactor(true);
        setUserId(response.userId || "");
        return;
      }

      navigate("/dashboard");
    } catch (err) {
      setErrorMessage(getAuthErrorMessage(err, "Unable to log in."));
    } finally {
      setIsSubmitting(false);
    }
  };

  // Step 2: Send userId and code to the verification endpoint (100% HttpOnly cookies, no localStorage)
  const handleVerify2Fa = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    setErrorMessage(null);
    setIsSubmitting(true);
    try {
      await axios.post("/api/auth/2fa/authenticate", {
        userId,
        code,
      });

      await refreshUser();
      navigate("/dashboard");
    } catch (err) {
      setErrorMessage(getAuthErrorMessage(err, "The 2FA code is invalid or has expired."));
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <section className="auth-panel">
      <div className="auth-content">
        <div className="mb-4 flex h-10 w-10 items-center justify-center rounded-card bg-surface-raised text-xl text-secondary shadow-sm">
          É
        </div>
        <h1 className="text-3xl font-normal text-text sm:text-4xl">
          {requiresTwoFactor ? "2FA Verification" : "Welcome back."}
        </h1>
        <p className="mt-2 text-sm leading-relaxed text-muted">
          {requiresTwoFactor
            ? "Enter the 6-digit code generated by your authenticator app."
            : "Access your dashboard, manage your projects, and connect with your peers."}
        </p>

        {/* IF 2FA IS NOT REQUIRED: Show email and password form */}
        {!requiresTwoFactor ? (
          <>
            <div className="mt-5">
              <button
                type="button"
                onClick={() => {
                  oauth42();
                }}
                className="auth-secondary-button"
              >
                <span className="flex h-5 w-5 items-center justify-center rounded-control bg-primary-soft text-xs font-bold text-background">
                  42
                </span>
                Continue with 42
              </button>
            </div>

            <div className="my-5 flex items-center gap-4 text-center font-sans text-[10px] font-semibold uppercase tracking-widest text-muted">
              <hr className="flex-1 border-border" />
              or continue with email
              <hr className="flex-1 border-border" />
            </div>

            <form onSubmit={handleSubmit} className="space-y-3.5">
              {errorMessage && <AuthErrorAlert message={errorMessage} />}
              <label className="auth-label">
                <span className="mb-1 block">Email address</span>
                <div className="auth-input-shell">
                  <Mail />
                  <input
                    type="email"
                    placeholder="user@domain.com"
                    value={email}
                    onChange={(e) => setEmail(e.target.value)}
                    required
                    className="auth-input"
                  />
                </div>
              </label>

              <label className="auth-label">
                <span className="mb-1 block">Password</span>
                <div className="auth-input-shell">
                  <Lock />
                  <input
                    type={showPassword ? "text" : "password"}
                    placeholder="••••••••••••"
                    value={password}
                    onChange={(e) => setPassword(e.target.value)}
                    required
                    className="auth-input tracking-widest placeholder:tracking-normal"
                  />
                  <button
                    type="button"
                    onClick={() => setShowPassword(!showPassword)}
                    className="text-muted transition-colors hover:text-text-soft"
                  >
                    {showPassword ? <EyeOpen /> : <EyeClose />}
                  </button>
                </div>
              </label>

              <button
                type="submit"
                disabled={isSubmitting}
                className="auth-button mt-2"
              >
                {isSubmitting ? "Connecting..." : "Log in"}
                <Arrow />
              </button>
            </form>

            <Link
              to="/register"
              className="auth-outline-button mt-4"
            >
              Don&apos;t have an account? Create account
            </Link>
          </>
        ) : (
          /* IF 2FA IS REQUIRED: Show only the 6-digit code input */
          <form onSubmit={handleVerify2Fa} className="mt-6 space-y-4">
            {errorMessage && <AuthErrorAlert message={errorMessage} />}
            <label className="auth-label">
              <span className="mb-1 block">Security code</span>
              <div className="auth-input-shell">
                <Lock />
                <input
                  type="text"
                  maxLength={6}
                  autoFocus
                  placeholder="123456"
                  value={code}
                  onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
                  required
                  className="auth-input text-center text-xl font-bold tracking-[0.3em]"
                />
              </div>
            </label>

            <button
              type="submit"
              disabled={code.length !== 6 || isSubmitting}
              className="auth-button mt-2 w-full disabled:opacity-50"
            >
              Verify and log in
              <Arrow />
            </button>

            <button
              type="button"
              onClick={() => {
                setRequiresTwoFactor(false);
                setCode("");
              }}
              className="auth-outline-button mt-2 w-full text-xs text-muted"
            >
              Go back
            </button>
          </form>
        )}
      </div>

      <footer className="mt-auto flex items-center justify-center gap-4 pt-4 font-sans text-[11px] text-muted">
        <Link to="/terms" className="hover:text-text-soft">
          Terms of service
        </Link>
        <span className="h-1 w-1 rounded-full bg-border"></span>
        <Link to="/privacy" className="hover:text-text-soft">
          Privacy Policy
        </Link>
      </footer>
    </section>
  );
}